//! The asset pipeline (NWS-2952): icons and image fills from the mirror to
//! files the stack uses directly, plus the manifest `figmog spec` reads.
//!
//! Pure: the CLI (`cli::assets`) reads the subtrees, the component
//! inventory and the image bytes (cache or Figma), and writes the files;
//! everything in between — which nodes are icons, their names, the
//! sanitized SVG, the React components, the content-hashed image names and
//! the manifest — is a function of those inputs here, so a re-export of an
//! unchanged file produces identical bytes.
//!
//! **Untrusted input.** Node names, ids, imageRefs and SVG markup come from
//! the Figma file and end up in code and file names:
//!
//! - component names are derived from ASCII letters and digits only (every
//!   other character separates words), always start with the configured
//!   prefix (validated as an identifier) and are capped at
//!   [`MAX_COMPONENT`] characters; names that collide — case-insensitively,
//!   for case-insensitive filesystems — skip every icon involved;
//! - node ids and imageRefs must match a strict character set before they
//!   reach a comment, a manifest or a file name; Figma names never reach
//!   generated code at all (only the manifest, as JSON-escaped data);
//! - image files are named only by the SHA-256 of their bytes and an
//!   extension sniffed from those bytes (PNG, JPEG, GIF, WebP — anything
//!   else is skipped);
//! - SVG markup goes through [`crate::svg::sanitize`].
//!
//! **Fidelity.** `currentColor` conversion is opt-in (`[assets]
//! current_color`) and applies only to an icon with exactly one flat paint
//! color ([`crate::svg::Sanitized::single_color`]); multicolor icons,
//! logos, gradients and filters keep their colors. Each component prefixes
//! its gradient, mask, clip-path and filter ids with React's `useId()`, so
//! repeated instances on one page never share an id.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use serde_json::{Map, Value, json};

use crate::project::{AssetSettings, ComponentLang, check_project_path};
use crate::svg::Sanitized;

/// The first line of every generated text file (inside the comment syntax
/// of its language); the CLI never overwrites a file that doesn't carry
/// it (unless `--force`).
pub(crate) const GENERATED: &str =
    "Generated by `figmog assets export` - do not edit; rerun the command to update.";
/// Longest generated component name.
pub(crate) const MAX_COMPONENT: usize = 64;
/// Longest Figma name considered.
const MAX_FIGMA_NAME: usize = 512;
/// Manifest format version.
const MANIFEST_VERSION: u64 = 1;

/// The manifest's generated marker key (sorts first in the JSON).
pub(crate) const MANIFEST_MARKER: &str = "$generated";

/// The generated-file header of a `.tsx`/`.jsx`/`.ts`/`.js` file.
pub(crate) fn js_header() -> String {
    format!("// {GENERATED}\n")
}

/// The generated-file header of an `.svg` file.
pub(crate) fn svg_header() -> String {
    format!("<!-- {GENERATED} -->\n")
}

/// The generated-file header of the manifest (its first two lines).
pub(crate) fn manifest_header() -> String {
    format!("{{\n  \"{MANIFEST_MARKER}\": \"{GENERATED}\"")
}

/// Whether `bytes` start with one of figmog's generated-file headers.
pub(crate) fn is_generated(bytes: &[u8]) -> bool {
    [js_header(), svg_header(), manifest_header()]
        .iter()
        .any(|h| bytes.starts_with(h.as_bytes()))
}

// ---- hashing and sniffing ----

/// SHA-256 of `data`, as lowercase hex (`ring`, already compiled in
/// through rustls).
pub(crate) fn sha256_hex(data: &[u8]) -> String {
    ring::digest::digest(&ring::digest::SHA256, data)
        .as_ref()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// The raster format `bytes` are, from their magic number — never from a
/// URL or name.
pub(crate) fn sniff(bytes: &[u8]) -> Option<&'static str> {
    if bytes.starts_with(b"\x89PNG\r\n\x1a\n") {
        Some("png")
    } else if bytes.starts_with(&[0xff, 0xd8, 0xff]) {
        Some("jpg")
    } else if bytes.starts_with(b"GIF87a") || bytes.starts_with(b"GIF89a") {
        Some("gif")
    } else if bytes.len() >= 12 && &bytes[..4] == b"RIFF" && &bytes[8..12] == b"WEBP" {
        Some("webp")
    } else {
        None
    }
}

// ---- untrusted identifiers ----

/// A Figma node id as figmog accepts it in generated output: `1:2`,
/// `I1:2;3:4`, at most 128 characters.
pub(crate) fn is_node_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 128
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, ':' | ';' | '-'))
}

/// A Figma imageRef: ASCII letters and digits, at most 128.
pub(crate) fn is_image_ref(r: &str) -> bool {
    !r.is_empty() && r.len() <= 128 && r.chars().all(|c| c.is_ascii_alphanumeric())
}

/// A generated component name: a capital ASCII letter, then ASCII letters
/// and digits, at most [`MAX_COMPONENT`].
pub(crate) fn is_component_name(name: &str) -> bool {
    name.len() <= MAX_COMPONENT
        && name.starts_with(|c: char| c.is_ascii_uppercase())
        && name.chars().all(|c| c.is_ascii_alphanumeric())
}

/// Words of ASCII letters and digits, each capitalized, joined.
fn pascal(raw: &str) -> String {
    raw.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut cs = w.chars();
            let first = cs.next().expect("words are non-empty");
            first.to_ascii_uppercase().to_string() + cs.as_str()
        })
        .collect()
}

/// Windows device names (`CON`, `PRN`, `AUX`, `NUL`, `COM1`–`COM9`,
/// `LPT1`–`LPT9`, any case): not usable as a file stem there.
fn is_reserved_stem(name: &str) -> bool {
    let upper = name.to_ascii_uppercase();
    matches!(upper.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        || ((upper.starts_with("COM") || upper.starts_with("LPT"))
            && upper.len() == 4
            && matches!(upper.as_bytes()[3], b'1'..=b'9'))
}

/// The component name for an icon named `raw` (already reduced to the
/// words that name it): PascalCase, starting with `prefix` (not doubled
/// when the name already starts with it as a word).
pub(crate) fn component_name(prefix: &str, raw: &str) -> Result<String, String> {
    if raw.len() > MAX_FIGMA_NAME {
        return Err(format!(
            "the Figma name is {} bytes long (limit {MAX_FIGMA_NAME})",
            raw.len()
        ));
    }
    let base = pascal(raw);
    if base.is_empty() {
        return Err("the Figma name has no ASCII letters or digits to name a component".into());
    }
    let has_prefix = base.strip_prefix(prefix).is_some_and(|rest| {
        rest.is_empty() || rest.starts_with(|c: char| c.is_ascii_uppercase() || c.is_ascii_digit())
    });
    let name = if has_prefix {
        base
    } else {
        format!("{prefix}{base}")
    };
    if is_reserved_stem(&name) {
        return Err(format!(
            "component name {name} is a reserved file name on Windows — rename the icon in Figma or change [assets] prefix"
        ));
    }
    if name.len() > MAX_COMPONENT {
        return Err(format!(
            "component name {}… is longer than {MAX_COMPONENT} characters",
            &name[..MAX_COMPONENT]
        ));
    }
    debug_assert!(is_component_name(&name));
    Ok(name)
}

// ---- finding icons and image fills ----

/// What the component inventory (`figmog_components`) says about a node.
#[derive(Debug, Default, Clone)]
pub(crate) struct Inventory {
    /// Component node id → its published key.
    pub(crate) keys: BTreeMap<String, String>,
    /// Variant component node id → its component set's name.
    pub(crate) set_names: BTreeMap<String, String>,
}

impl Inventory {
    /// From a `figmog_components` answer.
    pub(crate) fn from_components(v: &Value) -> Inventory {
        let mut inv = Inventory::default();
        for set in v["sets"].as_array().into_iter().flatten() {
            let set_name = set["name"].as_str().unwrap_or_default();
            if let (Some(id), Some(key)) = (set["node_id"].as_str(), set["key"].as_str()) {
                inv.keys.insert(id.into(), key.into());
            }
            for variant in set["variants"].as_array().into_iter().flatten() {
                let Some(id) = variant["node_id"].as_str() else {
                    continue;
                };
                inv.set_names.insert(id.into(), set_name.into());
                if let Some(key) = variant["key"].as_str() {
                    inv.keys.insert(id.into(), key.into());
                }
            }
        }
        for c in v["components"].as_array().into_iter().flatten() {
            if let (Some(id), Some(key)) = (c["node_id"].as_str(), c["key"].as_str()) {
                inv.keys.insert(id.into(), key.into());
            }
        }
        inv
    }
}

/// One icon found under an icon root.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct IconSource {
    pub(crate) node_id: String,
    /// The Figma name shown in the manifest (`Set / Variant` for a
    /// variant).
    pub(crate) figma_name: String,
    /// The words the component name is built from.
    naming: String,
}

/// The last `/`-separated segment of a Figma name (`icons/arrow-right` →
/// `arrow-right`): groups are organization, not identity.
fn last_segment(name: &str) -> &str {
    name.rsplit('/').next().unwrap_or(name).trim()
}

/// A variant's naming words: its set's name, then its property values
/// (`Name=Arrow Right, Size=24` → `Arrow Right 24`).
fn variant_naming(set_name: &str, variant: &str) -> String {
    let values: Vec<&str> = variant
        .split(',')
        .map(|part| part.split_once('=').map_or(part, |(_, v)| v).trim())
        .collect();
    format!("{} {}", last_segment(set_name), values.join(" "))
}

fn source_for(n: &Value, set_name: Option<&str>) -> IconSource {
    let id = n["id"].as_str().unwrap_or_default().to_string();
    let name = n["name"].as_str().unwrap_or_default();
    match set_name {
        Some(set) => IconSource {
            node_id: id,
            figma_name: format!("{set} / {name}"),
            naming: variant_naming(set, name),
        },
        None => IconSource {
            node_id: id,
            figma_name: name.to_string(),
            naming: last_segment(name).to_string(),
        },
    }
}

fn hidden(n: &Value) -> bool {
    n["visible"] == false
}

fn has_components(n: &Value) -> bool {
    n["children"].as_array().into_iter().flatten().any(|c| {
        !hidden(c)
            && (matches!(c["type"].as_str(), Some("COMPONENT" | "COMPONENT_SET"))
                || has_components(c))
    })
}

/// The icons under one icon root (the `figmog_subtree` answer for it):
///
/// - a component set: each visible variant;
/// - a page, section, frame or group holding components: each visible
///   component set's variants and each visible standalone component, at
///   any depth (a component's own content is never searched);
/// - anything else (a component, an instance, a vector, a frame of
///   vectors): the node itself is one icon.
pub(crate) fn find_icons(tree: &Value, inventory: &Inventory) -> Vec<IconSource> {
    fn walk(n: &Value, inv: &Inventory, out: &mut Vec<IconSource>) {
        for c in n["children"].as_array().into_iter().flatten() {
            if hidden(c) {
                continue;
            }
            match c["type"].as_str() {
                Some("COMPONENT_SET") => set(c, out),
                Some("COMPONENT") => {
                    let id = c["id"].as_str().unwrap_or_default();
                    out.push(source_for(c, inv.set_names.get(id).map(String::as_str)));
                }
                _ => walk(c, inv, out),
            }
        }
    }
    fn set(n: &Value, out: &mut Vec<IconSource>) {
        let set_name = n["name"].as_str().unwrap_or_default();
        for v in n["children"].as_array().into_iter().flatten() {
            if !hidden(v) && v["type"] == "COMPONENT" {
                out.push(source_for(v, Some(set_name)));
            }
        }
    }
    let mut out = Vec::new();
    match tree["type"].as_str() {
        Some("COMPONENT_SET") => set(tree, &mut out),
        Some("CANVAS" | "SECTION" | "FRAME" | "GROUP" | "DOCUMENT") if has_components(tree) => {
            walk(tree, inventory, &mut out)
        }
        _ => {
            let id = tree["id"].as_str().unwrap_or_default();
            out.push(source_for(
                tree,
                inventory.set_names.get(id).map(String::as_str),
            ));
        }
    }
    out
}

/// Every visible `IMAGE` fill's imageRef under `tree`, with the visible
/// nodes that use it.
pub(crate) fn find_image_fills(tree: &Value, out: &mut BTreeMap<String, BTreeSet<String>>) {
    if hidden(tree) {
        return;
    }
    let id = tree["id"].as_str().unwrap_or_default();
    for paint in tree["fills"].as_array().into_iter().flatten() {
        if paint["type"] == "IMAGE"
            && paint["visible"] != false
            && let Some(r) = paint["imageRef"].as_str()
        {
            out.entry(r.to_string()).or_default().insert(id.to_string());
        }
    }
    for c in tree["children"].as_array().into_iter().flatten() {
        find_image_fills(c, out);
    }
}

// ---- generated code ----

/// The React component for one icon.
pub(crate) fn react_component(
    name: &str,
    node_id: &str,
    svg: &Sanitized,
    lang: ComponentLang,
) -> String {
    debug_assert!(is_component_name(name) && is_node_id(node_id));
    let mut out = js_header();
    out.push_str(&format!("// Figma node {node_id}.\n"));
    let ids = svg.has_ids();
    if ids {
        out.push_str("import { useId } from \"react\";\n");
    }
    let props = match lang {
        ComponentLang::Tsx => {
            out.push_str("import type { SVGProps } from \"react\";\n");
            "props: SVGProps<SVGSVGElement>"
        }
        ComponentLang::Jsx => "props",
    };
    out.push('\n');
    out.push_str(&format!("export function {name}({props}) {{\n"));
    if ids {
        // `useId` is unique per rendered instance; its punctuation varies
        // across React versions and isn't id/url()-safe, so it is reduced
        // to letters, digits, `_` and `-` (still unique: the punctuation
        // only delimits).
        out.push_str("  const uid = `figmog${useId().replace(/[^A-Za-z0-9_-]/g, \"\")}`;\n");
    }
    out.push_str("  return (\n");
    out.push_str(&svg.to_jsx(
        2,
        "uid",
        &[
            "aria-hidden={props[\"aria-label\"] || props[\"aria-labelledby\"] ? undefined : true}",
            "{...props}",
        ],
    ));
    out.push_str("  );\n}\n\n");
    out.push_str(&format!("export default {name};\n"));
    out
}

/// The barrel file re-exporting every component.
fn barrel(names: &[&str]) -> String {
    let mut out = js_header();
    for name in names {
        out.push_str(&format!("export {{ {name} }} from \"./{name}\";\n"));
    }
    out
}

// ---- the export plan ----

/// One icon's input: where it came from and its rendered SVG (or why
/// there is none).
pub(crate) struct IconInput {
    pub(crate) source: IconSource,
    pub(crate) svg: Result<Vec<u8>, String>,
}

/// One image fill's input.
pub(crate) struct ImageInput {
    pub(crate) image_ref: String,
    pub(crate) nodes: BTreeSet<String>,
    pub(crate) bytes: Result<Vec<u8>, String>,
}

/// What a generated file is, for the overwrite check.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Kind {
    /// Text carrying a generated-file header.
    Generated,
    /// An image named by its own content hash.
    Content,
}

/// Every file an export writes, by project-relative path, plus the
/// command's report.
#[derive(Debug)]
pub(crate) struct Plan {
    pub(crate) files: BTreeMap<String, (Kind, Vec<u8>)>,
    pub(crate) icons: Vec<Value>,
    pub(crate) images: Vec<Value>,
    pub(crate) skipped: Vec<Value>,
}

/// What an export starts from — the Figma file and the root node ids —
/// kept in the manifest so a plain `figmog assets export` repeats it (and
/// node ids are only ever read against the file they belong to).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub(crate) struct Sources {
    /// The file key (none for a store with no known key).
    pub(crate) file: Option<String>,
    pub(crate) icons: Vec<String>,
    pub(crate) images: Vec<String>,
}

fn join(dir: &str, file: &str) -> String {
    format!("{}/{file}", dir.trim_end_matches('/'))
}

/// The URL an image in `dir` is served at, when `dir` is under `public/`
/// (the Vite / Next.js static folder, served from `/`).
fn public_url(dir: &str, file: &str) -> Option<String> {
    let dir = dir.trim_end_matches('/');
    let relative = if dir == "public" {
        file.to_string()
    } else {
        format!("{}/{file}", dir.strip_prefix("public/")?)
    };
    let mut url = String::from("/");
    for byte in relative.bytes() {
        if byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'.' | b'_' | b'~' | b'/') {
            url.push(char::from(byte));
        } else {
            use std::fmt::Write;
            write!(url, "%{byte:02X}").expect("writing a string");
        }
    }
    Some(url)
}

fn skip(kind: &str, subject: (&str, &str), reason: String) -> Value {
    let mut v = json!({"kind": kind, "reason": reason});
    v[subject.0] = json!(subject.1);
    v
}

/// Turn the fetched inputs into files. Deterministic: icons and images
/// are deduplicated by node id / imageRef and sorted by name / ref.
pub(crate) fn plan(
    settings: &AssetSettings,
    icons: Vec<IconInput>,
    images: Vec<ImageInput>,
    sources: &Sources,
    inventory: &Inventory,
) -> Plan {
    let mut skipped = Vec::new();
    let ext = settings.components.as_str();

    // Icons: name, sanitize, then refuse collisions.
    struct Ready {
        source: IconSource,
        name: String,
        svg: Sanitized,
        colors: &'static str,
        converted: bool,
    }
    let mut by_id: BTreeMap<String, IconInput> = BTreeMap::new();
    for icon in icons {
        by_id.entry(icon.source.node_id.clone()).or_insert(icon);
    }
    let mut ready: Vec<Ready> = Vec::new();
    for (id, icon) in by_id {
        if !is_node_id(&id) {
            skipped.push(skip("icon", ("node_id", &id), "not a valid node id".into()));
            continue;
        }
        let name = match component_name(&settings.prefix, &icon.source.naming) {
            Ok(name) => name,
            Err(e) => {
                skipped.push(skip("icon", ("node_id", &id), e));
                continue;
            }
        };
        let svg = icon.svg.and_then(|bytes| {
            let text = String::from_utf8(bytes).map_err(|_| "the SVG is not UTF-8".to_string())?;
            crate::svg::sanitize(&text)
        });
        let mut svg = match svg {
            Ok(svg) => svg,
            Err(e) => {
                skipped.push(skip("icon", ("node_id", &id), e));
                continue;
            }
        };
        let single = svg.single_color();
        let converted = settings.current_color
            && single
                .as_deref()
                .is_some_and(|color| svg.use_current_color(color));
        ready.push(Ready {
            source: icon.source,
            name,
            svg,
            colors: if single.is_some() { "single" } else { "multi" },
            converted,
        });
    }
    let mut by_name: BTreeMap<String, Vec<usize>> = BTreeMap::new();
    for (i, r) in ready.iter().enumerate() {
        by_name
            .entry(r.name.to_ascii_lowercase())
            .or_default()
            .push(i);
    }
    let mut colliding = BTreeSet::new();
    for group in by_name.values().filter(|g| g.len() > 1) {
        let ids: Vec<&str> = group
            .iter()
            .map(|i| ready[*i].source.node_id.as_str())
            .collect();
        for i in group {
            colliding.insert(*i);
            let r = &ready[*i];
            skipped.push(skip(
                "icon",
                ("node_id", &r.source.node_id),
                format!(
                    "component name {} collides (case-insensitively) with the icons of nodes {} — rename one in Figma",
                    r.name,
                    ids.join(", ")
                ),
            ));
        }
    }
    let mut ready: Vec<Ready> = ready
        .into_iter()
        .enumerate()
        .filter(|(i, _)| !colliding.contains(i))
        .map(|(_, r)| r)
        .collect();
    ready.sort_by(|a, b| a.name.cmp(&b.name));

    let mut files: BTreeMap<String, (Kind, Vec<u8>)> = BTreeMap::new();
    let mut icon_rows = Vec::new();
    let mut manifest_icons = Vec::new();
    for r in &ready {
        let component_path = join(&settings.icons, &format!("{}.{ext}", r.name));
        let svg_path = join(&settings.icons, &format!("svg/{}.svg", r.name));
        let svg_text = format!("{}{}", svg_header(), r.svg.to_svg(&r.name));
        files.insert(svg_path.clone(), (Kind::Generated, svg_text.into_bytes()));
        files.insert(
            component_path.clone(),
            (
                Kind::Generated,
                react_component(&r.name, &r.source.node_id, &r.svg, settings.components)
                    .into_bytes(),
            ),
        );
        let key = inventory.keys.get(&r.source.node_id);
        manifest_icons.push(json!({
            "component": r.name,
            "figma_name": shorten(&r.source.figma_name),
            "file": sources.file,
            "key": key,
            "node_id": r.source.node_id,
            "path": component_path,
            "svg": svg_path,
            "colors": r.colors,
            "current_color": r.converted,
        }));
        icon_rows.push(json!({
            "component": r.name,
            "node_id": r.source.node_id,
            "path": component_path,
            "svg": svg_path,
            "colors": r.colors,
            "current_color": r.converted,
            "removed": r.svg.removed,
        }));
    }
    if !ready.is_empty() {
        let names: Vec<&str> = ready.iter().map(|r| r.name.as_str()).collect();
        let index = if settings.components == ComponentLang::Tsx {
            "index.ts"
        } else {
            "index.js"
        };
        files.insert(
            join(&settings.icons, index),
            (Kind::Generated, barrel(&names).into_bytes()),
        );
    }

    // Images: content-addressed.
    let mut image_rows = Vec::new();
    let mut manifest_images = Vec::new();
    let mut by_ref: BTreeMap<String, ImageInput> = BTreeMap::new();
    for image in images {
        match by_ref.get_mut(&image.image_ref) {
            Some(existing) => existing.nodes.extend(image.nodes),
            None => {
                by_ref.insert(image.image_ref.clone(), image);
            }
        }
    }
    for (r, image) in by_ref {
        if !is_image_ref(&r) {
            skipped.push(skip(
                "image",
                ("image_ref", &r),
                "not a valid imageRef".into(),
            ));
            continue;
        }
        let bytes = match image.bytes {
            Ok(bytes) => bytes,
            Err(e) => {
                skipped.push(skip("image", ("image_ref", &r), e));
                continue;
            }
        };
        let Some(format) = sniff(&bytes) else {
            skipped.push(skip(
                "image",
                ("image_ref", &r),
                "not a PNG, JPEG, GIF or WebP image".into(),
            ));
            continue;
        };
        let sha = sha256_hex(&bytes);
        let file = format!("{}.{format}", &sha[..16]);
        let path = join(&settings.images, &file);
        let url = public_url(&settings.images, &file);
        let nodes: Vec<&String> = image.nodes.iter().filter(|n| is_node_id(n)).collect();
        if let Some((_, existing)) = files.get(&path)
            && *existing != bytes
        {
            skipped.push(skip(
                "image",
                ("image_ref", &r),
                format!("content hash prefix collides at {path}"),
            ));
            continue;
        }
        let row = json!({
            "file": sources.file,
            "image_ref": r,
            "path": path,
            "url": url,
            "format": format,
            "bytes": bytes.len(),
            "sha256": sha,
            "nodes": nodes,
        });
        files.insert(path, (Kind::Content, bytes));
        manifest_images.push(row.clone());
        image_rows.push(row);
    }

    let manifest = json!({
        MANIFEST_MARKER: GENERATED,
        "version": MANIFEST_VERSION,
        "sources": {"file": sources.file, "icons": sources.icons, "images": sources.images},
        "icons": manifest_icons,
        "images": manifest_images,
    });
    let mut text = serde_json::to_string_pretty(&manifest).expect("JSON values serialize");
    text.push('\n');
    debug_assert!(text.starts_with(&manifest_header()));
    files.insert(
        settings.manifest.clone(),
        (Kind::Generated, text.into_bytes()),
    );
    skipped.sort_by_key(|a| a.to_string());
    Plan {
        files,
        icons: icon_rows,
        images: image_rows,
        skipped,
    }
}

/// A Figma name as the manifest keeps it: at most [`MAX_FIGMA_NAME`]
/// bytes (cut at a character boundary, `…` appended).
fn shorten(name: &str) -> String {
    if name.len() <= MAX_FIGMA_NAME {
        return name.to_string();
    }
    let mut end = MAX_FIGMA_NAME;
    while !name.is_char_boundary(end) {
        end -= 1;
    }
    format!("{}…", &name[..end])
}

