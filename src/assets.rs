/// The icon entries of a manifest, as `figmog spec` uses them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct IconRef {
    /// The file `node_id` belongs to (none: unknown).
    pub(crate) file: Option<String>,
    pub(crate) node_id: String,
    pub(crate) key: Option<String>,
    pub(crate) component: String,
    pub(crate) path: String,
    pub(crate) svg: String,
}

/// The image entries of a manifest, as `figmog spec` uses them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ImageRef {
    pub(crate) image_ref: String,
    pub(crate) path: String,
    pub(crate) url: Option<String>,
}

/// A validated asset manifest: what `figmog spec` references instead of
/// raw node ids and imageRefs (`figmog_spec`'s `assets` argument).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub(crate) struct AssetIndex {
    pub(crate) icons: Vec<IconRef>,
    pub(crate) images: Vec<ImageRef>,
    pub(crate) sources: Sources,
    /// The file the spec using this index describes, as the CLI and the
    /// relay resolved it ([`AssetIndex::for_file`]): an icon is matched
    /// by node id only when it was exported from this file.
    pub(crate) for_file: Option<String>,
}

/// An optional Figma file key field.
fn file_field(o: &Map<String, Value>, key: &str, at: &str) -> Result<Option<String>, String> {
    match o.get(key) {
        None | Some(Value::Null) => Ok(None),
        Some(Value::String(k)) if crate::ident::is_file_key(k) => Ok(Some(k.clone())),
        Some(_) => Err(format!("{at}{key}: expected a Figma file key or null")),
    }
}

fn field<'a>(o: &'a Map<String, Value>, key: &str, at: &str) -> Result<&'a str, String> {
    o.get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("{at}.{key}: expected a string"))
}

fn path_field(o: &Map<String, Value>, key: &str, at: &str) -> Result<String, String> {
    let p = field(o, key, at)?;
    check_project_path(p).map_err(|e| format!("{at}.{key}: {e}"))?;
    Ok(p.to_string())
}

fn ids(v: Option<&Value>, at: &str) -> Result<Vec<String>, String> {
    let Some(v) = v else {
        return Ok(Vec::new());
    };
    let list = v.as_array().ok_or(format!("{at}: expected an array"))?;
    list.iter()
        .enumerate()
        .map(|(i, id)| match id.as_str() {
            Some(id) if is_node_id(id) => Ok(id.to_string()),
            _ => Err(format!("{at}[{i}]: expected a node id")),
        })
        .collect()
}

impl AssetIndex {
    /// Read the manifest at `<project root>/<manifest>`: `Ok(None)` when
    /// there is none; every error names the file.
    pub(crate) fn load(project_root: &Path, manifest: &str) -> Result<Option<AssetIndex>, String> {
        let path = project_root.join(manifest);
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(format!("{manifest}: {e}")),
        };
        let value: Value = serde_json::from_str(&text).map_err(|e| format!("{manifest}: {e}"))?;
        AssetIndex::from_json(&value, manifest).map(Some)
    }

    /// Validate a manifest (or `figmog_spec`'s normalized `assets`
    /// argument). Keys this reader doesn't use are ignored; the ones it
    /// uses are checked strictly. `origin` prefixes every error.
    pub(crate) fn from_json(value: &Value, origin: &str) -> Result<AssetIndex, String> {
        AssetIndex::parse(value).map_err(|e| format!("{origin}: {e}"))
    }

    fn parse(value: &Value) -> Result<AssetIndex, String> {
        let root = value.as_object().ok_or("$: expected an object")?;
        match root.get("version") {
            None => {}
            Some(v) if v.as_u64() == Some(MANIFEST_VERSION) => {}
            Some(v) => {
                return Err(format!(
                    "version: unsupported {v} (this figmog reads version {MANIFEST_VERSION})"
                ));
            }
        }
        let mut index = AssetIndex::default();
        let list = |key: &str| -> Result<Vec<Value>, String> {
            match root.get(key) {
                None => Ok(Vec::new()),
                Some(Value::Array(a)) => Ok(a.clone()),
                Some(_) => Err(format!("{key}: expected an array")),
            }
        };
        for (i, v) in list("icons")?.iter().enumerate() {
            let at = format!("icons[{i}]");
            let o = v.as_object().ok_or(format!("{at}: expected an object"))?;
            let node_id = field(o, "node_id", &at)?;
            if !is_node_id(node_id) {
                return Err(format!("{at}.node_id: not a node id"));
            }
            let component = field(o, "component", &at)?;
            if !is_component_name(component) {
                return Err(format!("{at}.component: not a component name"));
            }
            let key = match o.get("key") {
                None | Some(Value::Null) => None,
                Some(Value::String(k)) if is_image_ref(k) => Some(k.clone()),
                Some(_) => return Err(format!("{at}.key: expected a component key or null")),
            };
            index.icons.push(IconRef {
                file: file_field(o, "file", &format!("{at}."))?,
                node_id: node_id.into(),
                key,
                component: component.into(),
                path: path_field(o, "path", &at)?,
                svg: path_field(o, "svg", &at)?,
            });
        }
        for (i, v) in list("images")?.iter().enumerate() {
            let at = format!("images[{i}]");
            let o = v.as_object().ok_or(format!("{at}: expected an object"))?;
            let image_ref = field(o, "image_ref", &at)?;
            if !is_image_ref(image_ref) {
                return Err(format!("{at}.image_ref: not an imageRef"));
            }
            let url = match o.get("url") {
                None | Some(Value::Null) => None,
                Some(Value::String(u))
                    if u.starts_with('/')
                        && check_project_path(&u[1..]).is_ok()
                        && u.chars().all(|c| c.is_ascii_graphic()) =>
                {
                    Some(u.clone())
                }
                Some(_) => return Err(format!("{at}.url: expected a root-relative URL or null")),
            };
            index.images.push(ImageRef {
                image_ref: image_ref.into(),
                path: path_field(o, "path", &at)?,
                url,
            });
        }
        if let Some(s) = root.get("sources") {
            let s = s.as_object().ok_or("sources: expected an object")?;
            index.sources = Sources {
                file: file_field(s, "file", "sources.")?,
                icons: ids(s.get("icons"), "sources.icons")?,
                images: ids(s.get("images"), "sources.images")?,
            };
        }
        index.for_file = file_field(root, "for_file", "")?;
        Ok(index)
    }

    /// Files a previous export generated, including the barrel implied
    /// by each icon component's directory and language. Deriving barrels
    /// also covers manifests written before they were inventoried.
    pub(crate) fn generated_paths(&self) -> BTreeSet<String> {
        let mut paths = BTreeSet::new();
        for icon in &self.icons {
            paths.insert(icon.path.clone());
            paths.insert(icon.svg.clone());
            let index = if icon.path.ends_with(".tsx") {
                "index.ts"
            } else if icon.path.ends_with(".jsx") {
                "index.js"
            } else {
                continue;
            };
            paths.insert(match icon.path.rsplit_once('/') {
                Some((dir, _)) => join(dir, index),
                None => index.to_string(),
            });
        }
        paths.extend(self.images.iter().map(|i| i.path.clone()));
        paths
    }

    /// This index for a spec of file `target` (none: unknown — no icon is
    /// then matched by node id).
    pub(crate) fn for_file(mut self, target: Option<&str>) -> AssetIndex {
        self.for_file = target.map(str::to_string);
        self
    }

    /// The normalized index, as `figmog_spec`'s `assets` argument;
    /// [`AssetIndex::from_json`] reads it back to `self` (without
    /// `sources`, which spec doesn't use).
    pub(crate) fn to_json(&self) -> Value {
        json!({
            "version": MANIFEST_VERSION,
            "for_file": self.for_file,
            "icons": self.icons.iter().map(|i| json!({
                "file": i.file,
                "node_id": i.node_id,
                "key": i.key,
                "component": i.component,
                "path": i.path,
                "svg": i.svg,
            })).collect::<Vec<_>>(),
            "images": self.images.iter().map(|i| json!({
                "image_ref": i.image_ref,
                "path": i.path,
                "url": i.url,
            })).collect::<Vec<_>>(),
        })
    }

    /// The icon exported from the component with `key`, else from node
    /// `node_id` — the latter only for an icon exported from the file this
    /// index is [for](AssetIndex::for_file) (keys are the same in every
    /// file that uses a library component; node ids are file-local and
    /// repeat across files).
    pub(crate) fn icon(&self, key: Option<&str>, node_id: &str) -> Option<&IconRef> {
        key.and_then(|k| self.icons.iter().find(|i| i.key.as_deref() == Some(k)))
            .or_else(|| {
                let file = self.for_file.as_deref()?;
                self.icons
                    .iter()
                    .find(|i| i.node_id == node_id && i.file.as_deref() == Some(file))
            })
    }

    /// The exported image of `image_ref`.
    pub(crate) fn image(&self, image_ref: &str) -> Option<&ImageRef> {
        self.images.iter().find(|i| i.image_ref == image_ref)
    }
}

