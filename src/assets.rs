    #[test]
    fn manifest_round_trips_and_rejects_unsafe_entries() {
        let mut inv = Inventory::default();
        inv.keys.insert("1:2".into(), "abc".into());
        let p = plan(
            &settings(),
            vec![icon("1:2", "star", ICON)],
            vec![ImageInput {
                image_ref: "ff00".into(),
                nodes: BTreeSet::new(),
                bytes: Ok(b"GIF89a".to_vec()),
            }],
            &Sources {
                file: Some("figmogassetsfilea1".into()),
                icons: vec!["1:1".into()],
                images: vec!["2:1".into()],
            },
            &inv,
        );
        let manifest: Value = serde_json::from_slice(&p.files["figmog.assets.json"].1).unwrap();
        // Node ids match only for the file they came from; keys always.
        let index = AssetIndex::from_json(&manifest, "m").unwrap();
        assert_eq!(index.sources.file.as_deref(), Some("figmogassetsfilea1"));
        assert!(
            index.icon(None, "1:2").is_none(),
            "no target file: no node-id match"
        );
        let other = index.clone().for_file(Some("figmogassetsfileb2"));
        assert!(other.icon(None, "1:2").is_none(), "another file's 1:2");
        assert_eq!(
            other.icon(Some("abc"), "1:2").unwrap().component,
            "IconStar"
        );
        let index = index.for_file(Some("figmogassetsfilea1"));
        assert_eq!(index.icons[0].component, "IconStar");
        assert_eq!(index.icon(Some("abc"), "9:9").unwrap().node_id, "1:2");
        assert_eq!(index.icon(None, "1:2").unwrap().component, "IconStar");
        assert_eq!(index.sources.icons, ["1:1"]);
        let normalized = AssetIndex::from_json(&index.to_json(), "assets").unwrap();
        assert_eq!(normalized.icons, index.icons);
        assert_eq!(normalized.images, index.images);

        for (bad, needle) in [
            (
                json!({"icons": [{"node_id": "1:2", "component": "x; alert(1)", "path": "a", "svg": "b"}]}),
                "icons[0].component",
            ),
            (
                json!({"icons": [{"node_id": "1:2", "component": "IconA", "path": "../a", "svg": "b"}]}),
                "icons[0].path",
            ),
            (
                json!({"icons": [{"node_id": "1:2", "component": "IconA", "path": "/etc/passwd", "svg": "b"}]}),
                "icons[0].path",
            ),
            (
                json!({"images": [{"image_ref": "a/b", "path": "x.png"}]}),
                "images[0].image_ref",
            ),
            (
                json!({"images": [{"image_ref": "ab", "path": "x.png", "url": "javascript:alert(1)"}]}),
                "images[0].url",
            ),
            (json!({"version": 2}), "version"),
        ] {
            let e = AssetIndex::from_json(&bad, "m").unwrap_err();
            assert!(e.starts_with(&format!("m: {needle}")), "{e}");
        }
    }

